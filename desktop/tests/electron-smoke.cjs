const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

module.exports = async function smoke(win, root, backend, guardState, full) {
  const results = [];
  const js = code => win.webContents.executeJavaScript(code);
  const waitFor = async (predicate, label, ms = 20000) => {
    const limit = Date.now() + ms;
    while (Date.now() < limit) {
      if (await predicate()) return;
      await new Promise(resolve => setTimeout(resolve, 200));
    }
    throw new Error(`Timeout: ${label}`);
  };
  const check = (condition, label) => { assert.ok(condition, label); results.push(label); };
  const click = id => js(`document.getElementById(${JSON.stringify(id)}).click()`);
  await waitFor(async () => { try { await backend('health'); return true; } catch { return false; } }, 'backend health');
  await waitFor(() => js(`document.querySelectorAll('.question').length === 3`), 'questions');
  const sandbox = await js(`({node:typeof window.require, process:typeof window.process, bridge:typeof window.proctor.request, token:typeof window.PROCTOR_TOKEN})`);
  check(sandbox.node === 'undefined' && sandbox.process === 'undefined' && sandbox.token === 'undefined' && sandbox.bridge === 'function', 'Renderer sandbox and secret isolation');
  const denied = await js(`window.proctor.request('http://example.test').then(()=>false,()=>true)`);
  check(denied, 'Arbitrary IPC route rejected');
  check(await js(`window.open('https://example.test') === null`), 'Extra window denied');
  const folder = path.join(root, 'docs'); fs.mkdirSync(folder, { recursive: true });
  fs.writeFileSync(path.join(folder, 'ui-idle.png'), (await win.webContents.capturePage()).toPNG());
  check((await backend('status')).phase === 'idle', 'Camera remains off before explicit click');
  if (full) {
    await click('start-camera');
    await waitFor(async () => (await backend('status')).phase === 'running', 'CV startup');
    await waitFor(() => js(`!document.getElementById('calibrate').disabled`), 'calibration button');
    await click('calibrate');
    await waitFor(async () => (await backend('status')).calibrated, '5-frame calibration', 18000);
    check((await backend('status')).calibrated, 'Actual model calibration completed');
    await waitFor(() => js(`!document.getElementById('start-exam').disabled`), 'exam start ready in UI');
    await js(`document.getElementById('teacher-pin').value='908172';document.getElementById('teacher-pin').dispatchEvent(new Event('input'))`);
    const concurrentRejected = await js(`document.getElementById('start-exam').click();window.proctor.request('guard-start',{pin:'123456'}).then(()=>false,()=>true)`);
    check(concurrentRejected, 'Concurrent guard-start cannot create another helper');
    await waitFor(() => Promise.resolve(guardState().active), 'native guard startup');
    check(guardState().active, 'Kiosk and native guards active in Xvfb');
    check(await js(`window.proctor.request('guard-start',{pin:'123456'}).then(()=>false,()=>true)`), 'Active guard-start cannot replace teacher PIN');
    await waitFor(() => js(`!document.getElementById('frame').hidden`), 'real CV frame');
    fs.writeFileSync(path.join(folder, 'ui-overview.png'), (await win.webContents.capturePage()).toPNG());
    for(const key of ['ctrl+c','ctrl+v','alt+Tab','Super_L','Print'])execFileSync('xdotool', ['key', key]);
    await waitFor(() => Promise.resolve(['c','v','Tab','Super_L','Print'].every(key=>guardState().journal.some(e=>e.kind==='blocked_key'&&e.message===key))), 'native requested keys');
    check(true, 'Native Ctrl+C, Ctrl+V, Alt+Tab, Win and PrtScn intercepted and journaled');
    await click('submit');
    await waitFor(()=>js(`document.getElementById('notice').textContent.includes('Ответьте на каждый')`),'empty answers validation');
    check(!(await backend('exam')).submitted,'Empty answer submission remains blocked');
    await click('finish');
    check(await js(`document.getElementById('pin-dialog').open`), 'Teacher dialog opens');
    await click('pin-cancel');
    check(await js(`!document.getElementById('pin-dialog').open`), 'Teacher dialog cancel works');
    await click('finish');
    await js(`document.getElementById('finish-pin').value='000000'`);
    await click('pin-confirm');
    await waitFor(() => js(`document.getElementById('pin-error').textContent.length > 0`), 'invalid PIN');
    check(guardState().active, 'Wrong PIN preserves guards');
    await js(`document.getElementById('finish-pin').value='908172'`);
    await click('pin-confirm');
    await waitFor(() => Promise.resolve(!guardState().active), 'teacher release');
    check(!guardState().active, 'Correct teacher PIN releases kiosk and grabs');
    await waitFor(() => js(`!document.getElementById('start-exam').disabled`), 'restart ready');
    await click('start-exam');
    await waitFor(() => js(`document.getElementById('notice').classList.contains('error')`), 'empty PIN rejected');
    check(!guardState().active, 'Exam cannot restart without teacher PIN');
    await js(`document.getElementById('teacher-pin').value='908172'`);
    await click('start-exam');
    await waitFor(() => Promise.resolve(guardState().active), 'second guard startup');
    await js(`for(const name of ['q1','q2','q3'])document.querySelector('input[name="'+name+'"][value="A"]').checked=true`);
    await click('submit');
    await waitFor(() => js(`!document.getElementById('result').hidden`), 'exam submission');
    check((await backend('exam')).submitted, 'Answers persist and submit through real API');
    await waitFor(async () => {
      const state = await backend('status');
      return ['phone_present', 'second_face', 'face_absent'].every(kind => state.event_counts?.[kind] > 0);
    }, 'real phone/two-face/absence events', 35000);
    check(true, 'Real phone, second-face and absent-face events reached journal');
    check(guardState().active, 'Guards remain active until emergency control is used');
    execFileSync('xdotool', ['key', 'ctrl+alt+shift+q']);
    await waitFor(() => Promise.resolve(!guardState().active && guardState().aborted), 'emergency release');
    await waitFor(async () => (await backend('status')).phase === 'stopped', 'emergency CV stop');
    check(guardState().aborted, 'Emergency exit marks exam aborted and stops CV');
    check(guardState().journal.some(e=>e.kind==='guard_abort'&&e.message.includes('Ctrl+Alt+Shift+Q')), 'Actual emergency shortcut callback executed');
    check((await backend('status')).security_counts.fullscreen_left > 0, 'Abort remains in backend review journal');
    await waitFor(()=>js(`!document.getElementById('start-camera').disabled`),'camera restart button');
    await click('start-camera');
    await waitFor(async()=> (await backend('status')).phase==='running','camera restart');
    check(await js(`!exam.submitted && document.getElementById('result').hidden && !document.querySelector('input[type=radio]:checked')`),'New session clears preceding answers and result');
    await waitFor(()=>js(`!document.getElementById('stop-camera').disabled`),'stop camera button');
    await click('stop-camera');
    await waitFor(async()=> (await backend('status')).phase==='stopped','explicit camera stop');
    check((await backend('status')).phase==='stopped','Stop observation control stops the real capture worker');
  }
  win.setSize(620, 900);
  await new Promise(resolve => setTimeout(resolve, 300));
  check(await js(`document.documentElement.scrollWidth <= innerWidth`), '620px layout has no horizontal overflow');
  win.webContents.setZoomFactor(2);
  await new Promise(resolve=>setTimeout(resolve,300));
  check(await js(`document.documentElement.scrollWidth <= innerWidth`), '200 percent zoom reflows without horizontal overflow');
  win.webContents.setZoomFactor(1);
  await new Promise(resolve=>setTimeout(resolve,300));
  await js(`document.getElementById('exit').focus()`);
  check(await js(`document.activeElement.id==='exit' && getComputedStyle(document.activeElement).outlineStyle !== 'none'`), 'Keyboard focus remains visible');
  win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Tab' });
  win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Tab' });
  check(await js(`document.activeElement.tagName !== 'BODY'`), 'Tab reaches an interactive control');
  fs.writeFileSync(path.join(folder, 'ui-narrow.png'), (await win.webContents.capturePage()).toPNG());
  await js(`document.querySelector('details summary').click()`);
  check(await js(`document.querySelector('details').open`),'Limitations details control opens');
  check(await js(`document.getElementById('camera').max==='8'`),'Camera index control matches backend range');
  console.log('SMOKE_PASS', JSON.stringify(results));
  fs.writeFileSync(path.join(folder, 'desktop-smoke.json'), JSON.stringify({ pass: true, isolated: 'Xvfb', checks: results, windows_tested: false }, null, 2));
  await click('exit');
};
